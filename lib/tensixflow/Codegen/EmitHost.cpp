  os << "      for (uint32_t col = 0; col < kLogicalK; ++col) {\n";
  os << "        activationPadded[row * kK + col] = activation[row * kLogicalK + col];\n";
  os << "      }\n";
  os << "    }\n";
  os << "    std::vector<bfloat16> weightPadded(kK * kN, bfloat16(0.0f));\n";
