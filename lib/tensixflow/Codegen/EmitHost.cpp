  os << "// L1 tile layout is four 16x16 faces in row-major order, not one row-major\n";
  os << "// 32x32 block. Host-built constant tiles use the same addressing.\n";
  os << "std::size_t tileElement(uint32_t row, uint32_t col) {\n";
  os << "  const std::size_t face =\n";
  os << "      static_cast<std::size_t>(row / FACE_HEIGHT) * 2 + col / FACE_WIDTH;\n";
  os << "  return face * FACE_HEIGHT * FACE_WIDTH +\n";
  os << "         static_cast<std::size_t>(row % FACE_HEIGHT) * FACE_WIDTH +\n";
  os << "         col % FACE_WIDTH;\n";
  os << "}\n\n";
  os << "// Pack a per-column vector into row-replicated tiles, one tile per column\n";
  os << "// block. The compute kernel adds or multiplies these tiles against a\n";
  os << "// destination tile, so every row repeats the same column values.\n";
  os << "std::vector<bfloat16> packRowConstantTiles(const std::vector<float>& values,\n";
  os << "                                           uint32_t tileCount) {\n";
