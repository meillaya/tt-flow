  os << "      value = bfloat16(inputDistribution(rng));\n";
  os << "    }\n";
  os << "    for (bfloat16& value : w1) {\n";
  os << "      value = bfloat16(weightDistribution(rng));\n";
  os << "    }\n";
  os << "    for (bfloat16& value : w2) {\n";
  os << "      value = bfloat16(weightDistribution(rng));\n";
  os << "    }\n";
  os << "    for (bfloat16& value : residual) {\n";
  os << "      value = bfloat16(residualDistribution(rng));\n";
  os << "    }\n";
  os << "    for (float& value : gamma) {\n";
  os << "      value = gammaDistribution(rng);\n";
  os << "    }\n";
  os << "    for (float& value : bias) {\n";
  os << "      value = biasDistribution(rng);\n";
  os << "    }\n\n";
  os << "    // CPU golden on the row-major operands.\n";
