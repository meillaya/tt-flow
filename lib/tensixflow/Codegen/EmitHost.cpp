  os << "    std::vector<bfloat16> result(static_cast<std::size_t>(kM) * kN,\n";
  os << "                                 bfloat16(0.0f));\n";
  os << "    runMlp(meshDevice, activationTiles, gammaTiles, scalerTiles, w1Tiles,\n";
  os << "           biasTiles, w2Tiles, residualTiles, result);\n";
  os << "    result = untilize_nfaces(result, kM, kN);\n\n";
  os << "    const float correlation = pearsonCorrelation(paddedGolden, result);\n";
  os << "    const bool passed = correlation >= kPccThreshold;\n";
