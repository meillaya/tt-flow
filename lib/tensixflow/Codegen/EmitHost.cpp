namespace {

// One circular-buffer slot read off the schedule's parallel index/depth/
// tile-bytes arrays (the --tensixflow-allocate-circular-buffers output).
struct CbSpec {
  int64_t index;
  int64_t depth;
  int64_t tileBytes;
  int64_t bytes() const { return depth * tileBytes; }
};

// Read the schedule's parallel CB arrays into CbSpecs. Falls back to the
// documented 3-CB reader/compute/writer pipeline {0,1,16} when the arrays are
// absent/short so the emission is always a complete, compilable TU.
SmallVector<CbSpec> readCbSpecs(TensixflowScheduleAttr schedule) {
  SmallVector<CbSpec> cbs;
  ArrayAttr indices = schedule.getCbIndices();
  ArrayAttr depths = schedule.getCbDepths();
  ArrayAttr tileBytes = schedule.getCbTileBytes();
  unsigned n = indices.size();
  if (depths.size() < n)
    n = depths.size();
  if (tileBytes.size() < n)
    n = tileBytes.size();
  for (unsigned i = 0; i < n; ++i)
    cbs.push_back({cast<IntegerAttr>(indices[i]).getInt(),
                   cast<IntegerAttr>(depths[i]).getInt(),
                   cast<IntegerAttr>(tileBytes[i]).getInt()});
  if (cbs.size() < 3) {
    cbs.clear();
    cbs.push_back({0, 2, 2048});
    cbs.push_back({1, 2, 2048});
    cbs.push_back({16, 2, 2048});
  }
  return cbs;
}

// The tile-loop trip count driving a reader/compute/writer region (the first
// sched.tile_loop nested in it); 1 if the region is empty/absent.
int64_t tripCount(Operation *op) {
  int64_t trip = 1;
  if (op)
    op->walk([&](TensixflowSchedTileLoopOp loop) {
      trip = loop.getTripCount();
      return WalkResult::interrupt();
    });
  return trip;
}

} // namespace

void emitHost(TensixflowSchedKernelOp kernel, TensixflowScheduleAttr schedule,
              llvm::raw_ostream &os) {
  // Pull the reader/compute/writer tile programs off the schedule IR.
  TensixflowSchedReaderOp reader;
  TensixflowSchedComputeOp compute;
  TensixflowSchedWriterOp writer;
  kernel.walk([&](TensixflowSchedReaderOp op) { reader = op; });
  kernel.walk([&](TensixflowSchedComputeOp op) { compute = op; });
  kernel.walk([&](TensixflowSchedWriterOp op) { writer = op; });
  int64_t readerTrip = tripCount(reader);
  int64_t computeTrip = tripCount(compute);
  int64_t writerTrip = tripCount(writer);
  (void)readerTrip;
  (void)writerTrip;

  // Plan decisions read off the schedule attribute (never hardcoded).
  unsigned gridY = schedule.getGridY();
  unsigned gridX = schedule.getGridX();
  unsigned endX = gridX > 0 ? gridX - 1 : 0;
  unsigned endY = gridY > 0 ? gridY - 1 : 0;
  StringRef fusion = schedule.getFusion().getValue();
  StringRef weightStrategy = schedule.getWeightStrategy().getValue();
  SmallVector<CbSpec> cbs = readCbSpecs(schedule);
  const CbSpec &in0 = cbs[0];
  const CbSpec &in1 = cbs[1];
  const CbSpec &out = cbs[2];
  int64_t cbTotal = 0;
  for (const CbSpec &cb : cbs)
    cbTotal += cb.bytes();

  // --- Translation-unit prologue ------------------------------------------
  os << "//===- host.cpp - TensixFlow-generated host (current tt-metal API) ===//\n";
  os << "//\n";
  os << "// Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "// kernel: " << kernel.getSymName() << "  fusion: " << fusion
     << "  weight: " << weightStrategy << "  grid: " << gridY << "x" << gridX
     << "\n";
  os << "//\n";
  os << "// CURRENT tt-metal API only: single CreateKernel + config variant,\n";
  os << "// tt::CBIndex circular buffers, distributed::Enqueue* mesh enqueue.\n";
  os << "// The legacy program-enqueue API + per-role CreateKernel are intentionally absent.\n";
  os << "\n";
  os << "#include <cstdint>\n";
  os << "#include <memory>\n";
  os << "#include <vector>\n";
  os << "\n";
  os << "#include \"host_api.hpp\"\n";
  os << "\n";
  os << "namespace host {\n\n";
  os << "void run() {\n";
  os << "  using namespace tt::tt_metal;\n\n";

  // --- Device + program ---------------------------------------------------
  os << "  // Open a 1x1 (\"unit\") mesh device -- the no-hardware modeling entry point.\n";
  os << "  auto device = distributed::MeshDevice::create_unit_mesh(/*device_id=*/0);\n\n";
  os << "  Program program = CreateProgram();\n\n";
  os << "  // The core grid the kernel runs on (gridY x gridX).\n";
  os << "  CoreRange grid{CoreCoord{0, 0}, CoreCoord{" << endX << ", " << endY
     << "}};\n\n";

  // --- Kernels (single current CreateKernel + config variant) -------------
  os << "  // Compute kernel: HiFi4 matmul, fp32 accumulate; compile_args = K-tile trip.\n";
  os << "  ComputeConfig compute_config{\n";
  os << "      .math_fidelity = MathFidelity::HiFi4,\n";
  os << "      .fp32_dest_acc_en = true,\n";
  os << "      .compile_args = {" << computeTrip << "},\n";
  os << "  };\n";
  os << "  KernelHandle compute_kernel =\n";
  os << "      CreateKernel(program, \"compute.cpp\", grid, compute_config);\n\n";

  os << "  // Reader (data-movement, BRISC): stages activation + weight tiles into CBs.\n";
  os << "  DataMovementConfig reader_config{\n";
  os << "      .processor = DataMovementProcessor::RISCV_0,\n";
  os << "      .noc = NOC::RISCV_0_default,\n";
  os << "      .compile_args = {},\n";
  os << "  };\n";
  os << "  KernelHandle reader_kernel =\n";
  os << "      CreateKernel(program, \"reader.cpp\", grid, reader_config);\n\n";

  os << "  // Writer (data-movement, NCRISC): drains result tiles to the destination.\n";
  os << "  DataMovementConfig writer_config{\n";
  os << "      .processor = DataMovementProcessor::RISCV_1,\n";
  os << "      .noc = NOC::RISCV_1_default,\n";
  os << "      .compile_args = {},\n";
  os << "  };\n";
  os << "  KernelHandle writer_kernel =\n";
  os << "      CreateKernel(program, \"writer.cpp\", grid, writer_config);\n\n";

  // --- Circular buffers (tt::CBIndex; from the schedule allocation) -------
  os << "  // Circular buffers addressed by tt::CBIndex (from the schedule allocation).\n";
  os << "  CreateCircularBuffer(\n";
  os << "      program, grid,\n";
  os << "      CircularBufferConfig(" << cbTotal << ", {";
  for (unsigned i = 0; i < cbs.size(); ++i) {
    if (i != 0)
      os << ",";
    os << "{tt::CBIndex::c_" << cbs[i].index << ", " << cbs[i].bytes() << "}";
  }
  os << "}));\n\n";

  // --- DRAM buffers (interleaved) for the inputs + output -----------------
  // The plan's activation sharding is row-major and weight strategy multicast
  // for the running example, so both inputs are interleaved DRAM buffers; a
  // "shard" plan would select ShardedBufferConfig (a documented extension that
  // todo 37's project assembler reconciles with the emitted kernel addresses).
  os << "  // DRAM buffers (interleaved) for the activation + weight inputs and output.\n";
  os << "  auto in0 = CreateBuffer(device.get(),\n";
  os << "                          InterleavedBufferConfig{\n";
  os << "                              .size = " << in0.bytes() << ",\n";
  os << "                              .page_size = " << in0.tileBytes << ",\n";
  os << "                              .buffer_type = BufferType::DRAM,\n";
  os << "                          });\n";
  os << "  auto in1 = CreateBuffer(device.get(),\n";
  os << "                          InterleavedBufferConfig{\n";
  os << "                              .size = " << in1.bytes() << ",\n";
  os << "                              .page_size = " << in1.tileBytes << ",\n";
  os << "                              .buffer_type = BufferType::DRAM,\n";
  os << "                          });\n";
  os << "  auto out0 = CreateBuffer(device.get(),\n";
  os << "                           InterleavedBufferConfig{\n";
  os << "                               .size = " << out.bytes() << ",\n";
  os << "                               .page_size = " << out.tileBytes << ",\n";
  os << "                               .buffer_type = BufferType::DRAM,\n";
  os << "                           });\n\n";

  // --- Runtime args -------------------------------------------------------
  os << "  // Runtime args: the compute kernel's tile trip + per-core reader/writer args.\n";
  os << "  SetCommonRuntimeArgs(program, compute_kernel, {" << computeTrip << "});\n";
  os << "  SetRuntimeArgs(program, reader_kernel, grid, {0, 0, 0, 0, "
     << in0.tileBytes << "});\n";
  os << "  SetRuntimeArgs(program, writer_kernel, grid, {0, 0, 0, 0, "
     << out.tileBytes << "});\n\n";

  // --- Enqueue via the current distributed mesh API -----------------------
  os << "  // Enqueue via the current distributed mesh API.\n";
  os << "  distributed::CommandQueue cq{};\n";
  os << "  distributed::MeshWorkload workload{};\n";
  os << "  std::vector<std::uint32_t> src(" << in0.tileBytes << ", 0);\n";
  os << "  distributed::EnqueueWriteMeshBuffer(cq, in0, src);\n";
  os << "  distributed::EnqueueWriteMeshBuffer(cq, in1, src);\n";
  os << "  distributed::EnqueueMeshWorkload(cq, device, workload, /*blocking=*/true);\n";
  os << "  std::vector<std::uint32_t> dst;\n";
  os << "  distributed::EnqueueReadMeshBuffer(cq, dst, out0);\n";

  os << "}\n\n";
  os << "}  // namespace host\n";
}

