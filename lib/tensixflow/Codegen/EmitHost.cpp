//===- Codegen/EmitHost.cpp - Emit a tt-metal host.cpp ---------*- C++ -*-===//
//
// TensixFlow: An MLIR Compiler for Tile-Native LLM Kernels on
// Tenstorrent-Style Spatial Accelerators.
//
//===----------------------------------------------------------------------===//
//
// The host.cpp emitter. See include/tensixflow/Codegen/EmitHost.h for the
// contract. The emitted program follows the pinned tt-metal v0.82.0-rc2
// programming_examples/matmul/ structure: a unit mesh device, a mesh command
// queue, replicated DRAM buffers, a circular buffer pipeline on the plan's core
// grid, one reader / compute / writer kernel created with the single
// CreateKernel entry point, and the distributed::Enqueue* mesh calls. Which
// mapping the program realizes is the plan's decision: output-tile-ranges
// splits the output tiles with split_work_to_cores and passes each core its
// contiguous range, while blocked-reuse assigns a 2D block and passes its tile
// coordinates so the reader can stage the block's activation rows and weight
// columns once.
//
// The program is self-checking: deterministic inputs, a CPU reference matmul in
// fp32 with bf16 rounding, the device matmul, and a PCC print. The geometry
// comes from the tensixflow.matmul_shape attribute the lowering pass stamps on
// the sched.kernel; the circular-buffer indices and depths come from the plan.
//
// The emitted project is compiled, linked, and executed against the pinned
// release by scripts/build_generated.sh and scripts/run_generated.sh. It is not
// validated against stubs and no stub headers exist in this repository.
//
//===----------------------------------------------------------------------===//

