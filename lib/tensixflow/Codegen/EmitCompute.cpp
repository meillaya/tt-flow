// The fp32 bit pattern of a constant the compute kernel bakes into an SFPU
// instruction. The scalar SFPU ops take the fp32 value encoded as a uint32.
uint32_t floatBits(float value) {
  return llvm::bit_cast<uint32_t>(value);
}

// Numeric constants the fused compute kernel bakes in: the epsilon of the
// RMSNorm prologue and 1/K for the RMS mean.
struct FusedConstants {
  uint32_t epsilonBits = 0;
  uint32_t inverseKBits = 0;
};

FusedConstants readFusedConstants(TensixflowSchedKernelOp kernel,
                                  const MatmulShape &shape) {
  FusedConstants constants;
  FloatAttr epsilon = fusedEpsilon(kernel);
  const float epsilonValue =
      epsilon ? static_cast<float>(epsilon.getValueAsDouble()) : 1.0e-6f;
  constants.epsilonBits = floatBits(epsilonValue);
  constants.inverseKBits =
      floatBits(1.0f / static_cast<float>(shape.kTiles() * kEmitTileWidth));
  return constants;
}

void emitFusedCompute(TensixflowSchedKernelOp kernel,
                      TensixflowScheduleAttr schedule, const MatmulShape &shape,
                      llvm::raw_ostream &os) {
  llvm::SmallVector<CbSlot> slots = readCbSlots(schedule);
  const CbSlot &act = slots[kFusedActivationSlot];
  const CbSlot &weight = slots[kFusedWeightSlot];
  const CbSlot &gamma = slots[kFusedGammaSlot];
  const CbSlot &scaler = slots[kFusedScalerSlot];
  const CbSlot &norm = slots[kFusedNormalizedSlot];
  const CbSlot &out = slots[kFusedOutputSlot];
  const FusedConstants constants = readFusedConstants(kernel, shape);

  os << "//===- kernels/compute.cpp - TensixFlow-generated fused RMSNorm + ";
  os << "MatMul compute kernel ----===//\n";
  os << "//\n";
  os << "// Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "//\n";
  os << "// Role: fused compute (tile math). Each core normalizes the activation\n";
  os << "// rows of the output tiles it owns once in L1, then runs the matmul from\n";
  os << "// the normalized circular buffer. The normalized intermediate never\n";
  os << "// reaches DRAM.\n";
  os << "//\n";
  os << "// Op sequence per staged row, with " << shape.kTiles()
     << " reduction tiles:\n";
  os << "//   1. square each staged tile with mul_tiles and pack it;\n";
  os << "//   2. SUM / REDUCE_ROW reduce each squared tile into one destination\n";
  os << "//      tile with the unit scaler, then scale by 1/K, add epsilon and\n";
  os << "//      take the reciprocal square root (binop_with_scalar + rsqrt);\n";
  os << "//   3. pack the inverse RMS column with the reduce packer mask;\n";
  os << "//   4. multiply each staged tile by the inverse RMS column\n";
  os << "//      (mul_tiles_bcast_cols) and by the replicated gamma tile\n";
  os << "//      (dest-reuse multiply), then pack the normalized tiles;\n";
  os << "//   5. accumulate the row's output tiles in destination registers, one\n";
  os << "//      per output column tile, from the normalized buffer.\n";
  os << "//\n";
  os << "// Circular-buffer roles in the plan's fused allocation.\n";
  os << "//\n";
  os << "//===----------------------------------------------------------------------===//\n\n";
  os << "#include <cstdint>\n\n";
  os << "#include \"api/compute/bcast.h\"\n";
  os << "#include \"api/compute/cb_api.h\"\n";
  os << "#include \"api/compute/compute_kernel_hw_startup.h\"\n";
  os << "#include \"api/compute/eltwise_binary.h\"\n";
  os << "#include \"api/compute/eltwise_unary/binop_with_scalar.h\"\n";
  os << "#include \"api/compute/eltwise_unary/rsqrt.h\"\n";
  os << "#include \"api/compute/matmul.h\"\n";
  os << "#include \"api/compute/pack.h\"\n";
  os << "#include \"api/compute/reduce.h\"\n";
  os << "#include \"api/compute/reg_api.h\"\n";
  os << "#include \"api/compute/tile_move_copy.h\"\n";
  os << "#include \"hostdevcommon/kernel_structs.h\"\n\n";
  os << "using std::uint32_t;\n\n";
  os << "void kernel_main() {\n";
  os << "    // Runtime args: the first linear output-tile id this core owns and\n";
  os << "    // how many output tiles it owns.\n";
  os << "    const uint32_t startTile = get_arg_val<uint32_t>(0);\n";
  os << "    const uint32_t tileCount = get_arg_val<uint32_t>(1);\n";
  os << "    if (tileCount == 0) {\n";
  os << "        return;\n";
  os << "    }\n\n";
  os << "    // Tile geometry: the reduction and output column tile counts.\n";
  os << "    constexpr uint32_t kKt = " << shape.kTiles() << ";\n";
  os << "    constexpr uint32_t kNt = " << shape.nTiles() << ";\n";
  os << "    // Epsilon and 1/K as fp32 bit patterns for the SFPU scalar ops.\n";
  os << "    constexpr uint32_t kEpsilonBits = " << constants.epsilonBits
     << "u;\n";
  os << "    constexpr uint32_t kInverseKBits = " << constants.inverseKBits
     << "u;\n\n";
  os << "    // Circular-buffer indices from the plan's fused allocation.\n";
  os << "    constexpr tt::CBIndex cb_act = tt::CBIndex::c_" << act.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_weight = tt::CBIndex::c_" << weight.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_gamma = tt::CBIndex::c_" << gamma.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_scaler = tt::CBIndex::c_" << scaler.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_norm = tt::CBIndex::c_" << norm.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_out = tt::CBIndex::c_" << out.index
     << ";\n\n";
  os << "    // One-time hardware configuration, then the SFPU inits the scalar\n";
  os << "    // and reciprocal-square-root ops need.\n";
  os << "    compute_kernel_hw_startup<SrcOrder::Reverse>(cb_act, cb_weight, cb_out);\n";
  os << "    binop_with_scalar_tile_init();\n";
  os << "    rsqrt_tile_init();\n\n";
  os << "    // Gamma and the reduce scaler are resident for the whole kernel.\n";
  os << "    cb_wait_front(cb_gamma, kKt);\n";
  os << "    cb_wait_front(cb_scaler, 1);\n\n";
  os << "    // The core owns a contiguous linear output-tile range, so its rows\n";
  os << "    // are consecutive. Each staged row is normalized once, then consumed\n";
  os << "    // by every output column tile of that row in the range.\n";
  os << "    const uint32_t firstRow = startTile / kNt;\n";
  os << "    const uint32_t lastRow = (startTile + tileCount - 1) / kNt;\n";
  os << "    for (uint32_t row = firstRow; row <= lastRow; ++row) {\n";
  os << "        cb_wait_front(cb_act, kKt);\n\n";
  os << "        // 1. Stage one squared tile per K block. The reduce reads its\n";
  os << "        //    input from a circular buffer, so the squares round-trip\n";
  os << "        //    through L1 but never reach DRAM.\n";
  os << "        mul_init(cb_act, cb_act);\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            tile_regs_acquire();\n";
  os << "            mul_tiles(cb_act, cb_act, kt, kt, 0);\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            cb_reserve_back(cb_norm, 1);\n";
  os << "            pack_tile(0, cb_norm);\n";
  os << "            cb_push_back(cb_norm, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n\n";
  os << "        // 2. Row sum of squares: one REDUCE_ROW per squared tile\n";
  os << "        //    accumulates into the same destination tile. Scale by 1/K,\n";
  os << "        //    add epsilon, and take the reciprocal square root.\n";
  os << "        cb_wait_front(cb_norm, kKt);\n";
  os << "        reconfig_data_format(cb_scaler, cb_norm);\n";
  os << "        reduce_init<PoolType::SUM, ReduceDim::REDUCE_ROW>(cb_norm, cb_scaler, cb_norm);\n";
  os << "        tile_regs_acquire();\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            reduce_tile<PoolType::SUM, ReduceDim::REDUCE_ROW>(cb_norm, cb_scaler, kt, 0, 0);\n";
  os << "        }\n";
  os << "        cb_pop_front(cb_norm, kKt);\n";
  os << "        binop_with_scalar_tile_init();\n";
  os << "        mul_unary_tile(0, kInverseKBits);\n";
  os << "        add_unary_tile(0, kEpsilonBits);\n";
  os << "        rsqrt_tile_init();\n";
  os << "        rsqrt_tile(0);\n";
  os << "        tile_regs_commit();\n";
  os << "        tile_regs_wait();\n";
  os << "        cb_reserve_back(cb_norm, 1);\n";
  os << "        pack_tile(0, cb_norm);\n";
  os << "        cb_push_back(cb_norm, 1);\n";
  os << "        tile_regs_release();\n";
  os << "        reduce_uninit(cb_norm);\n\n";
  os << "        // 3. Apply the inverse RMS per row (column broadcast) and gamma\n";
  os << "        //    per column (elementwise multiply against the replicated\n";
  os << "        //    gamma tile). The inverse RMS tile sits behind the packed\n";
  os << "        //    normalized tiles and is popped before the last pack.\n";
  os << "        cb_wait_front(cb_norm, 1);\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            tile_regs_acquire();\n";
  os << "            mul_bcast_cols_init(cb_act, cb_norm);\n";
  os << "            mul_tiles_bcast_cols(cb_act, cb_norm, kt, 0, 0);\n";
  os << "            mul_reuse_dest_init<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(cb_gamma);\n";
  os << "            mul_reuse_dest_tiles<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(cb_gamma, kt, 0);\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            if (kt == kKt - 1) {\n";
  os << "                cb_pop_front(cb_norm, 1);\n";
  os << "            }\n";
  os << "            cb_reserve_back(cb_norm, 1);\n";
  os << "            pack_tile(0, cb_norm);\n";
  os << "            cb_push_back(cb_norm, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n";
  os << "        cb_pop_front(cb_act, kKt);\n\n";
  os << "        // 4. Matmul this row. The normalized tile at the front of the\n";
  os << "        //    normalized buffer is the A operand for every output column\n";
  os << "        //    tile, then it is popped, so all matmul reads use the front\n";
  os << "        //    tile. One destination register accumulates per column tile.\n";
  os << "        const uint32_t firstCol = (row == firstRow) ? startTile % kNt : 0;\n";
  os << "        const uint32_t lastCol =\n";
  os << "            (row == lastRow) ? (startTile + tileCount - 1) % kNt : kNt - 1;\n";
  os << "        matmul_init(cb_norm, cb_weight);\n";
  os << "        tile_regs_acquire();\n";
  os << "        binop_with_scalar_tile_init();\n";
  os << "        for (uint32_t col = firstCol; col <= lastCol; ++col) {\n";
  os << "            mul_unary_tile(col - firstCol, 0u /* 0.0f bit pattern */);\n";
  os << "        }\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            cb_wait_front(cb_norm, 1);\n";
  os << "            for (uint32_t col = firstCol; col <= lastCol; ++col) {\n";
  os << "                cb_wait_front(cb_weight, 1);\n";
  os << "                matmul_tiles(cb_norm, cb_weight, 0, 0, col - firstCol);\n";
  os << "                cb_pop_front(cb_weight, 1);\n";
  os << "            }\n";
  os << "            cb_pop_front(cb_norm, 1);\n";
  os << "        }\n";
  os << "        tile_regs_commit();\n";
  os << "        tile_regs_wait();\n";
  os << "        for (uint32_t col = firstCol; col <= lastCol; ++col) {\n";
  os << "            cb_reserve_back(cb_out, 1);\n";
  os << "            pack_tile(col - firstCol, cb_out);\n";
  os << "            cb_push_back(cb_out, 1);\n";
  os << "        }\n";
  os << "        tile_regs_release();\n";
  os << "    }\n\n";
  os << "    // Balance the resident constant buffers.\n";
  os << "    cb_pop_front(cb_gamma, kKt);\n";
  os << "    cb_pop_front(cb_scaler, 1);\n";
  os << "}\n";
}

// Emit the blocked-reuse compute kernel: wait for the full resident weight
// block once, then accumulate each output tile of the 2D block over K from the
// activation and weight tiles already in L1. One destination register holds the
// output tile under accumulation, so the kernel is independent of the block
// extent.
void emitBlockedReuseCompute(TensixflowScheduleAttr schedule,
                             llvm::raw_ostream &os) {
  llvm::SmallVector<CbSlot> slots = readCbSlots(schedule);
  const int64_t in0Index = slots[0].index;
  const int64_t in1Index = slots[1].index;
  const int64_t outIndex = slots[2].index;

  os << "//===- kernels/compute.cpp - TensixFlow-generated compute kernel ----===//\n";
  os << "//\n";
  os << "// Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "//\n";
  os << "// Role: compute (tile math), blocked-reuse mapping. The kernel waits once\n";
  os << "// for the core's resident activation row block and weight column block,\n";
  os << "// then accumulates each output tile of its 2D block over K from those\n";
  os << "// buffers and packs it. No input tile is reread for a second output tile.\n";
  os << "//\n";
  os << "// Derived from tt-metal v0.82.0-rc2\n";
  os << "// matmul_common/kernels/compute/bmm.cpp (Apache-2.0), restructured to read\n";
  os << "// the resident blocks this plan stages. The circular-buffer indices and the\n";
  os << "// per-core 2D block come from the TensixFlow plan.\n";
  os << "//\n";
  os << "//===----------------------------------------------------------------------===//\n\n";
  os << "#include <cstdint>\n\n";
  os << "#include \"api/compute/compute_kernel_hw_startup.h\"\n";
  os << "#include \"api/compute/matmul.h\"\n";
  os << "#include \"api/compute/tile_move_copy.h\"\n";
  os << "#include \"hostdevcommon/kernel_structs.h\"\n\n";
  os << "using std::uint32_t;\n\n";
  os << "void kernel_main() {\n";
  os << "    // Runtime args: the core's 2D block extent in output tiles and the\n";
  os << "    // reduction tile count.\n";
  os << "    const uint32_t rowCount = get_arg_val<uint32_t>(0);\n";
  os << "    const uint32_t colCount = get_arg_val<uint32_t>(1);\n";
  os << "    const uint32_t Kt = get_arg_val<uint32_t>(2);\n";
  os << "    if (rowCount == 0 || colCount == 0) {\n";
  os << "        return;\n";
  os << "    }\n\n";
  os << "    // Circular-buffer indices from the plan allocation.\n";
  os << "    constexpr tt::CBIndex cb_in0 = tt::CBIndex::c_" << in0Index << ";\n";
  os << "    constexpr tt::CBIndex cb_in1 = tt::CBIndex::c_" << in1Index << ";\n";
  os << "    constexpr tt::CBIndex cb_out = tt::CBIndex::c_" << outIndex << ";\n\n";
  os << "    // Configure the matrix engine for the input and output circular buffers.\n";
  os << "    compute_kernel_hw_startup<SrcOrder::Reverse>(cb_in0, cb_in1, cb_out);\n";
  os << "    matmul_init(cb_in0, cb_in1);\n\n";
  os << "    // The reader stages both blocks before the compute kernel starts the\n";
  os << "    // matmul, so one wait per block covers every output tile. The tile\n";
  os << "    // indices below are offsets from the front of the resident buffers.\n";
  os << "    cb_wait_front(cb_in0, rowCount * Kt);\n";
  os << "    cb_wait_front(cb_in1, Kt * colCount);\n\n";
  os << "    for (uint32_t mt = 0; mt < rowCount; ++mt) {\n";
  os << "        for (uint32_t nt = 0; nt < colCount; ++nt) {\n";
  os << "            tile_regs_acquire();\n";
  os << "            for (uint32_t kt = 0; kt < Kt; ++kt) {\n";
  os << "                matmul_tiles(cb_in0, cb_in1, mt * Kt + kt,\n";
  os << "                             kt * colCount + nt, 0);\n";
  os << "            }\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            cb_reserve_back(cb_out, 1);\n";
  os << "            pack_tile(0, cb_out);\n";
  os << "            cb_push_back(cb_out, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n";
  os << "    }\n";
  os << "}\n";
}


// The fused MLP compute kernel. It normalizes one staged activation row in L1,
// runs the first matmul with a resident weight block, adds the bias, applies an
// accurate GELU, packs the bf16 intermediate rows into an L1 buffer, then runs
// the second matmul from that buffer and adds the residual. The destination
// register holds one output tile at a time, so the column count is not bounded
// by the FP32 destination register file.
void emitMlpCompute(TensixflowSchedKernelOp kernel,
                    TensixflowScheduleAttr schedule, const MlpShape &shape,
                    const MatmulEmission &mapping, llvm::raw_ostream &os) {
  llvm::SmallVector<CbSlot> slots = readCbSlots(schedule);
  const CbSlot &act = slots[kMlpActivationRowSlot];
  const CbSlot &sq = slots[kMlpSquaredRowSlot];
  const CbSlot &invrms = slots[kMlpInverseRmsSlot];
  const CbSlot &norm = slots[kMlpNormalizedRowSlot];
  const CbSlot &w1 = slots[kMlpWeight1Slot];
  const CbSlot &gamma = slots[kMlpGammaSlot];
  const CbSlot &scaler = slots[kMlpScalerSlot];
  const CbSlot &bias = slots[kMlpBiasSlot];
  const CbSlot &w2 = slots[kMlpWeight2Slot];
  const CbSlot &residual = slots[kMlpResidualRowSlot];
  const CbSlot &inter = slots[kMlpIntermediateSlot];
  const CbSlot &out = slots[kMlpOutputSlot];

  FloatAttr epsilonAttr = fusedEpsilon(kernel);
  const float epsilonValue =
      epsilonAttr ? static_cast<float>(epsilonAttr.getValueAsDouble()) : 1.0e-6f;
  const uint32_t epsilonBits = floatBits(epsilonValue);
  const uint32_t inverseKBits =
      floatBits(1.0f / static_cast<float>(shape.kTiles() * kEmitTileWidth));

  os << "//===- kernels/compute.cpp - TensixFlow-generated fused MLP compute ";
  os << "kernel -----===//\n";
  os << "//\n";
  os << "// Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "//\n";
  os << "// Role: fused MLP compute (tile math). Per activation row: RMSNorm in L1,\n";
  os << "// matmul with w1, bias, accurate GELU, pack the bf16 intermediate; then per\n";
  os << "// output column: matmul with w2 from the L1 intermediate, residual add,\n";
  os << "// pack. The intermediate never reaches DRAM.\n";
  os << "//\n";
  os << "// Op sequence per row, with " << shape.kTiles()
     << " reduction tiles and " << shape.hTiles() << " hidden tiles:\n";
  os << "//   1. square each staged tile with mul_tiles and pack it to c_1;\n";
  os << "//   2. SUM / REDUCE_ROW reduce with the unit scaler, scale by 1/K, add\n";
  os << "//      epsilon, take the reciprocal square root, pack the inverse RMS;\n";
  os << "//   3. multiply by the inverse RMS column (mul_tiles_bcast_cols) and by the\n";
  os << "//      replicated gamma tile (dest-reuse multiply), pack the normalized row;\n";
  os << "//   4. matmul over Kt with the resident w1, add the bias with a dest-reuse\n";
  os << "//      add, apply the accurate GELU, pack the intermediate to c_10;\n";
  os << "//   5. per output column, matmul over Ht from the L1 intermediate, add the\n";
  os << "//      residual with a dest-reuse add, pack the output tile.\n";
  os << "//\n";
  os << "// Every circular buffer is read by tile index only while its front pointer\n";
  os << "// sits at the buffer base, so each push or pop cycle totals the depth.\n";
  os << "//\n";
  os << "//===----------------------------------------------------------------------===//\n\n";
  os << "#include <cstdint>\n\n";
  os << "#include \"api/compute/bcast.h\"\n";
  os << "#include \"api/compute/cb_api.h\"\n";
  os << "#include \"api/compute/compute_kernel_hw_startup.h\"\n";
  os << "#include \"api/compute/eltwise_binary.h\"\n";
  os << "#include \"api/compute/eltwise_unary/binop_with_scalar.h\"\n";
  os << "#include \"api/compute/eltwise_unary/gelu.h\"\n";
  os << "#include \"api/compute/eltwise_unary/rsqrt.h\"\n";
  os << "#include \"api/compute/matmul.h\"\n";
  os << "#include \"api/compute/pack.h\"\n";
  os << "#include \"api/compute/reduce.h\"\n";
  os << "#include \"api/compute/reg_api.h\"\n\n";
  os << "using std::uint32_t;\n\n";
  os << "void kernel_main() {\n";
  os << "    // Runtime args: this core's row and column block extents.\n";
  os << "    const uint32_t rowCount = get_arg_val<uint32_t>(0);\n";
  os << "    const uint32_t colCount = get_arg_val<uint32_t>(1);\n";
  os << "    if (rowCount == 0 || colCount == 0) {\n";
  os << "        return;\n";
  os << "    }\n\n";
  os << "    // Tile geometry: reduction, hidden, and output column tiles.\n";
  os << "    constexpr uint32_t kKt = " << shape.kTiles() << ";\n";
  os << "    constexpr uint32_t kHt = " << shape.hTiles() << ";\n";
  os << "    constexpr uint32_t kColsPerCore = " << mapping.colsPerCore << ";\n";
  os << "    // Epsilon and 1/K as fp32 bit patterns for the SFPU scalar ops.\n";
  os << "    constexpr uint32_t kEpsilonBits = " << epsilonBits << "u;\n";
  os << "    constexpr uint32_t kInverseKBits = " << inverseKBits << "u;\n\n";
  os << "    // Circular-buffer indices from the plan's fused MLP allocation.\n";
  os << "    constexpr tt::CBIndex cb_act = tt::CBIndex::c_" << act.index << ";\n";
  os << "    constexpr tt::CBIndex cb_sq = tt::CBIndex::c_" << sq.index << ";\n";
  os << "    constexpr tt::CBIndex cb_invrms = tt::CBIndex::c_" << invrms.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_norm = tt::CBIndex::c_" << norm.index << ";\n";
  os << "    constexpr tt::CBIndex cb_w1 = tt::CBIndex::c_" << w1.index << ";\n";
  os << "    constexpr tt::CBIndex cb_gamma = tt::CBIndex::c_" << gamma.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_scaler = tt::CBIndex::c_" << scaler.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_bias = tt::CBIndex::c_" << bias.index << ";\n";
  os << "    constexpr tt::CBIndex cb_w2 = tt::CBIndex::c_" << w2.index << ";\n";
  os << "    constexpr tt::CBIndex cb_residual = tt::CBIndex::c_" << residual.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_inter = tt::CBIndex::c_" << inter.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_out = tt::CBIndex::c_" << out.index << ";\n\n";
  os << "    compute_kernel_hw_startup<SrcOrder::Reverse>(cb_norm, cb_w1, cb_out);\n";
  os << "    binop_with_scalar_tile_init();\n";
  os << "    rsqrt_tile_init();\n\n";
  os << "    // Resident constant tiles are pushed once and indexed in place; their\n";
  os << "    // front pointer stays at the buffer base until the final pop.\n";
  os << "    cb_wait_front(cb_gamma, kKt);\n";
  os << "    cb_wait_front(cb_scaler, 1);\n";
  os << "    cb_wait_front(cb_w1, kKt * kHt);\n";
  os << "    cb_wait_front(cb_bias, kHt);\n";
  os << "    cb_wait_front(cb_w2, kHt * kColsPerCore);\n\n";
  os << "    for (uint32_t row = 0; row < rowCount; ++row) {\n";
  os << "        // Phase 1. Square each staged tile, then reduce the row sum of\n";
  os << "        // squares. A full pop cycle follows every push cycle.\n";
  os << "        cb_wait_front(cb_act, kKt);\n";
  os << "        mul_init(cb_act, cb_act);\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            tile_regs_acquire();\n";
  os << "            mul_tiles(cb_act, cb_act, kt, kt, 0);\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            cb_reserve_back(cb_sq, 1);\n";
  os << "            pack_tile(0, cb_sq);\n";
  os << "            cb_push_back(cb_sq, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n\n";
  os << "        cb_wait_front(cb_sq, kKt);\n";
  os << "        reconfig_data_format(cb_scaler, cb_sq);\n";
  os << "        reduce_init<PoolType::SUM, ReduceDim::REDUCE_ROW>(\n";
  os << "            cb_sq, cb_scaler, cb_invrms);\n";
  os << "        tile_regs_acquire();\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            reduce_tile<PoolType::SUM, ReduceDim::REDUCE_ROW>(\n";
  os << "                cb_sq, cb_scaler, kt, 0, 0);\n";
  os << "        }\n";
  os << "        cb_pop_front(cb_sq, kKt);\n";
  os << "        binop_with_scalar_tile_init();\n";
  os << "        mul_unary_tile(0, kInverseKBits);\n";
  os << "        add_unary_tile(0, kEpsilonBits);\n";
  os << "        rsqrt_tile_init();\n";
  os << "        rsqrt_tile(0);\n";
  os << "        tile_regs_commit();\n";
  os << "        tile_regs_wait();\n";
  os << "        cb_reserve_back(cb_invrms, 1);\n";
  os << "        pack_tile(0, cb_invrms);\n";
  os << "        cb_push_back(cb_invrms, 1);\n";
  os << "        tile_regs_release();\n";
  os << "        reduce_uninit(cb_invrms);\n\n";
  os << "        // Apply the inverse RMS per row, then gamma per column.\n";
  os << "        cb_wait_front(cb_invrms, 1);\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            tile_regs_acquire();\n";
  os << "            mul_bcast_cols_init(cb_act, cb_invrms);\n";
  os << "            mul_tiles_bcast_cols(cb_act, cb_invrms, kt, 0, 0);\n";
  os << "            mul_reuse_dest_init<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(\n";
  os << "                cb_gamma);\n";
  os << "            mul_reuse_dest_tiles<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(\n";
  os << "                cb_gamma, kt, 0);\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            if (kt == kKt - 1) {\n";
  os << "                cb_pop_front(cb_invrms, 1);\n";
  os << "            }\n";
  os << "            cb_reserve_back(cb_norm, 1);\n";
  os << "            pack_tile(0, cb_norm);\n";
  os << "            cb_push_back(cb_norm, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n";
  os << "        cb_pop_front(cb_act, kKt);\n\n";
  os << "        // Phase 2. First matmul, bias add, accurate GELU, then the bf16\n";
  os << "        // intermediate pack into the L1 buffer at this row's offset.\n";
  os << "        cb_wait_front(cb_norm, kKt);\n";
  os << "        for (uint32_t h = 0; h < kHt; ++h) {\n";
  os << "            matmul_init(cb_norm, cb_w1);\n";
  os << "            tile_regs_acquire();\n";
  os << "            binop_with_scalar_tile_init();\n";
  os << "            mul_unary_tile(0, 0u);\n";
  os << "            for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "                matmul_tiles(cb_norm, cb_w1, kt, kt * kHt + h, 0);\n";
  os << "            }\n";
  os << "            add_reuse_dest_init<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(\n";
  os << "                cb_bias);\n";
  os << "            add_reuse_dest_tiles<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(\n";
  os << "                cb_bias, h, 0);\n";
  os << "            gelu_tile_init</*fast_and_approx=*/false>();\n";
  os << "            gelu_tile</*fast_and_approx=*/false>(0);\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            cb_reserve_back(cb_inter, 1);\n";
  os << "            pack_tile(0, cb_inter);\n";
  os << "            cb_push_back(cb_inter, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n";
  os << "        cb_pop_front(cb_norm, kKt);\n";
  os << "    }\n\n";
  os << "    // Phase 3. Second matmul over Ht from the resident L1 intermediate,\n";
  os << "    // residual add, and output pack. The intermediate buffer is read only\n";
  os << "    // here, so its front pointer is still at the buffer base.\n";
  os << "    cb_wait_front(cb_inter, rowCount * kHt);\n";
  os << "    for (uint32_t row = 0; row < rowCount; ++row) {\n";
  os << "        cb_wait_front(cb_residual, kColsPerCore);\n";
  os << "        for (uint32_t localCol = 0; localCol < colCount; ++localCol) {\n";
  os << "            matmul_init(cb_inter, cb_w2);\n";
  os << "            tile_regs_acquire();\n";
  os << "            binop_with_scalar_tile_init();\n";
  os << "            mul_unary_tile(0, 0u);\n";
  os << "            for (uint32_t ht = 0; ht < kHt; ++ht) {\n";
  os << "                matmul_tiles(cb_inter, cb_w2, row * kHt + ht,\n";
  os << "                             ht * kColsPerCore + localCol, 0);\n";
  os << "            }\n";
  os << "            add_reuse_dest_init<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(\n";
  os << "                cb_residual);\n";
  os << "            add_reuse_dest_tiles<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(\n";
  os << "                cb_residual, localCol, 0);\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            cb_reserve_back(cb_out, 1);\n";
  os << "            pack_tile(0, cb_out);\n";
  os << "            cb_push_back(cb_out, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n";
  os << "        cb_pop_front(cb_residual, kColsPerCore);\n";
  os << "    }\n";
  os << "    cb_pop_front(cb_inter, rowCount * kHt);\n\n";
  os << "    // Balance the resident constant buffers.\n";
  os << "    cb_pop_front(cb_gamma, kKt);\n";
  os << "    cb_pop_front(cb_scaler, 1);\n";
  os << "    cb_pop_front(cb_w1, kKt * kHt);\n";
  os << "    cb_pop_front(cb_bias, kHt);\n";
  os << "    cb_pop_front(cb_w2, kHt * kColsPerCore);\n";
  os << "}\n";
}

