// The fp32 bit pattern of a constant the compute kernel bakes into an SFPU
// instruction. The scalar SFPU ops take the fp32 value encoded as a uint32.
uint32_t floatBits(float value) {
  return llvm::bit_cast<uint32_t>(value);
}

// Numeric constants the fused compute kernel bakes in: the epsilon of the
// RMSNorm prologue and 1/K for the RMS mean.
struct FusedConstants {
  uint32_t epsilonBits = 0;
  uint32_t inverseKBits = 0;
};

FusedConstants readFusedConstants(TensixflowSchedKernelOp kernel,
                                  const MatmulShape &shape) {
  FusedConstants constants;
  FloatAttr epsilon = fusedEpsilon(kernel);
  const float epsilonValue =
      epsilon ? static_cast<float>(epsilon.getValueAsDouble()) : 1.0e-6f;
  constants.epsilonBits = floatBits(epsilonValue);
  constants.inverseKBits =
      floatBits(1.0f / static_cast<float>(shape.kTiles() * kEmitTileWidth));
  return constants;
}

void emitFusedCompute(TensixflowSchedKernelOp kernel,
                      TensixflowScheduleAttr schedule, const MatmulShape &shape,
                      llvm::raw_ostream &os) {
  llvm::SmallVector<CbSlot> slots = readCbSlots(schedule);
  const CbSlot &act = slots[kFusedActivationSlot];
  const CbSlot &weight = slots[kFusedWeightSlot];
  const CbSlot &gamma = slots[kFusedGammaSlot];
  const CbSlot &scaler = slots[kFusedScalerSlot];
  const CbSlot &norm = slots[kFusedNormalizedSlot];
  const CbSlot &out = slots[kFusedOutputSlot];
  const FusedConstants constants = readFusedConstants(kernel, shape);

  os << "//===- kernels/compute.cpp - TensixFlow-generated fused RMSNorm + ";
  os << "MatMul compute kernel ----===//\n";
  os << "//\n";
  os << "// Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "//\n";
  os << "// Role: fused compute (tile math). Each core normalizes the activation\n";
  os << "// rows of the output tiles it owns once in L1, then runs the matmul from\n";
  os << "// the normalized circular buffer. The normalized intermediate never\n";
  os << "// reaches DRAM.\n";
  os << "//\n";
  os << "// Op sequence per staged row, with " << shape.kTiles()
     << " reduction tiles:\n";
  os << "//   1. square each staged tile with mul_tiles and pack it;\n";
  os << "//   2. SUM / REDUCE_ROW reduce each squared tile into one destination\n";
  os << "//      tile with the unit scaler, then scale by 1/K, add epsilon and\n";
  os << "//      take the reciprocal square root (binop_with_scalar + rsqrt);\n";
  os << "//   3. pack the inverse RMS column with the reduce packer mask;\n";
  os << "//   4. multiply each staged tile by the inverse RMS column\n";
  os << "//      (mul_tiles_bcast_cols) and by the replicated gamma tile\n";
  os << "//      (dest-reuse multiply), then pack the normalized tiles;\n";
  os << "//   5. accumulate the row's output tiles in destination registers, one\n";
  os << "//      per output column tile, from the normalized buffer.\n";
  os << "//\n";
  os << "// Circular-buffer roles in the plan's fused allocation.\n";
  os << "//\n";
  os << "//===----------------------------------------------------------------------===//\n\n";
  os << "#include <cstdint>\n\n";
  os << "#include \"api/compute/bcast.h\"\n";
  os << "#include \"api/compute/cb_api.h\"\n";
  os << "#include \"api/compute/compute_kernel_hw_startup.h\"\n";
  os << "#include \"api/compute/eltwise_binary.h\"\n";
  os << "#include \"api/compute/eltwise_unary/binop_with_scalar.h\"\n";
  os << "#include \"api/compute/eltwise_unary/rsqrt.h\"\n";
  os << "#include \"api/compute/matmul.h\"\n";
  os << "#include \"api/compute/pack.h\"\n";
  os << "#include \"api/compute/reduce.h\"\n";
  os << "#include \"api/compute/reg_api.h\"\n";
  os << "#include \"api/compute/tile_move_copy.h\"\n";
  os << "#include \"hostdevcommon/kernel_structs.h\"\n\n";
  os << "using std::uint32_t;\n\n";
  os << "void kernel_main() {\n";
  os << "    // Runtime args: the first linear output-tile id this core owns and\n";
  os << "    // how many output tiles it owns.\n";
  os << "    const uint32_t startTile = get_arg_val<uint32_t>(0);\n";
  os << "    const uint32_t tileCount = get_arg_val<uint32_t>(1);\n";
  os << "    if (tileCount == 0) {\n";
  os << "        return;\n";
  os << "    }\n\n";
  os << "    // Tile geometry: the reduction and output column tile counts.\n";
  os << "    constexpr uint32_t kKt = " << shape.kTiles() << ";\n";
  os << "    constexpr uint32_t kNt = " << shape.nTiles() << ";\n";
  os << "    // Epsilon and 1/K as fp32 bit patterns for the SFPU scalar ops.\n";
  os << "    constexpr uint32_t kEpsilonBits = " << constants.epsilonBits
     << "u;\n";
  os << "    constexpr uint32_t kInverseKBits = " << constants.inverseKBits
     << "u;\n\n";
  os << "    // Circular-buffer indices from the plan's fused allocation.\n";
  os << "    constexpr tt::CBIndex cb_act = tt::CBIndex::c_" << act.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_weight = tt::CBIndex::c_" << weight.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_gamma = tt::CBIndex::c_" << gamma.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_scaler = tt::CBIndex::c_" << scaler.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_norm = tt::CBIndex::c_" << norm.index
     << ";\n";
  os << "    constexpr tt::CBIndex cb_out = tt::CBIndex::c_" << out.index
     << ";\n\n";
  os << "    // One-time hardware configuration, then the SFPU inits the scalar\n";
  os << "    // and reciprocal-square-root ops need.\n";
  os << "    compute_kernel_hw_startup<SrcOrder::Reverse>(cb_act, cb_weight, cb_out);\n";
  os << "    binop_with_scalar_tile_init();\n";
  os << "    rsqrt_tile_init();\n\n";
  os << "    // Gamma and the reduce scaler are resident for the whole kernel.\n";
  os << "    cb_wait_front(cb_gamma, kKt);\n";
  os << "    cb_wait_front(cb_scaler, 1);\n\n";
  os << "    // The core owns a contiguous linear output-tile range, so its rows\n";
  os << "    // are consecutive. Each staged row is normalized once, then consumed\n";
  os << "    // by every output column tile of that row in the range.\n";
  os << "    const uint32_t firstRow = startTile / kNt;\n";
  os << "    const uint32_t lastRow = (startTile + tileCount - 1) / kNt;\n";
  os << "    for (uint32_t row = firstRow; row <= lastRow; ++row) {\n";
  os << "        cb_wait_front(cb_act, kKt);\n\n";
  os << "        // 1. Stage one squared tile per K block. The reduce reads its\n";
  os << "        //    input from a circular buffer, so the squares round-trip\n";
  os << "        //    through L1 but never reach DRAM.\n";
  os << "        mul_init(cb_act, cb_act);\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            tile_regs_acquire();\n";
  os << "            mul_tiles(cb_act, cb_act, kt, kt, 0);\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            cb_reserve_back(cb_norm, 1);\n";
  os << "            pack_tile(0, cb_norm);\n";
  os << "            cb_push_back(cb_norm, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n\n";
  os << "        // 2. Row sum of squares: one REDUCE_ROW per squared tile\n";
  os << "        //    accumulates into the same destination tile. Scale by 1/K,\n";
  os << "        //    add epsilon, and take the reciprocal square root.\n";
  os << "        cb_wait_front(cb_norm, kKt);\n";
  os << "        reconfig_data_format(cb_scaler, cb_norm);\n";
  os << "        reduce_init<PoolType::SUM, ReduceDim::REDUCE_ROW>(cb_norm, cb_scaler, cb_norm);\n";
  os << "        tile_regs_acquire();\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            reduce_tile<PoolType::SUM, ReduceDim::REDUCE_ROW>(cb_norm, cb_scaler, kt, 0, 0);\n";
  os << "        }\n";
  os << "        cb_pop_front(cb_norm, kKt);\n";
  os << "        binop_with_scalar_tile_init();\n";
  os << "        mul_unary_tile(0, kInverseKBits);\n";
  os << "        add_unary_tile(0, kEpsilonBits);\n";
  os << "        rsqrt_tile_init();\n";
  os << "        rsqrt_tile(0);\n";
  os << "        tile_regs_commit();\n";
  os << "        tile_regs_wait();\n";
  os << "        cb_reserve_back(cb_norm, 1);\n";
  os << "        pack_tile(0, cb_norm);\n";
  os << "        cb_push_back(cb_norm, 1);\n";
  os << "        tile_regs_release();\n";
  os << "        reduce_uninit(cb_norm);\n\n";
  os << "        // 3. Apply the inverse RMS per row (column broadcast) and gamma\n";
  os << "        //    per column (elementwise multiply against the replicated\n";
  os << "        //    gamma tile). The inverse RMS tile sits behind the packed\n";
  os << "        //    normalized tiles and is popped before the last pack.\n";
  os << "        cb_wait_front(cb_norm, 1);\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            tile_regs_acquire();\n";
  os << "            mul_bcast_cols_init(cb_act, cb_norm);\n";
  os << "            mul_tiles_bcast_cols(cb_act, cb_norm, kt, 0, 0);\n";
  os << "            mul_reuse_dest_init<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(cb_gamma);\n";
  os << "            mul_reuse_dest_tiles<EltwiseBinaryReuseDestType::DEST_TO_SRCA>(cb_gamma, kt, 0);\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            if (kt == kKt - 1) {\n";
  os << "                cb_pop_front(cb_norm, 1);\n";
  os << "            }\n";
  os << "            cb_reserve_back(cb_norm, 1);\n";
  os << "            pack_tile(0, cb_norm);\n";
  os << "            cb_push_back(cb_norm, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n";
  os << "        cb_pop_front(cb_act, kKt);\n\n";
  os << "        // 4. Matmul this row. The normalized tile at the front of the\n";
  os << "        //    normalized buffer is the A operand for every output column\n";
  os << "        //    tile, then it is popped, so all matmul reads use the front\n";
  os << "        //    tile. One destination register accumulates per column tile.\n";
  os << "        const uint32_t firstCol = (row == firstRow) ? startTile % kNt : 0;\n";
  os << "        const uint32_t lastCol =\n";
  os << "            (row == lastRow) ? (startTile + tileCount - 1) % kNt : kNt - 1;\n";
  os << "        matmul_init(cb_norm, cb_weight);\n";
  os << "        tile_regs_acquire();\n";
  os << "        binop_with_scalar_tile_init();\n";
  os << "        for (uint32_t col = firstCol; col <= lastCol; ++col) {\n";
  os << "            mul_unary_tile(col - firstCol, 0u /* 0.0f bit pattern */);\n";
  os << "        }\n";
  os << "        for (uint32_t kt = 0; kt < kKt; ++kt) {\n";
  os << "            cb_wait_front(cb_norm, 1);\n";
  os << "            for (uint32_t col = firstCol; col <= lastCol; ++col) {\n";
  os << "                cb_wait_front(cb_weight, 1);\n";
  os << "                matmul_tiles(cb_norm, cb_weight, 0, 0, col - firstCol);\n";
  os << "                cb_pop_front(cb_weight, 1);\n";
  os << "            }\n";
  os << "            cb_pop_front(cb_norm, 1);\n";
  os << "        }\n";
  os << "        tile_regs_commit();\n";
  os << "        tile_regs_wait();\n";
  os << "        for (uint32_t col = firstCol; col <= lastCol; ++col) {\n";
  os << "            cb_reserve_back(cb_out, 1);\n";
  os << "            pack_tile(col - firstCol, cb_out);\n";
  os << "            cb_push_back(cb_out, 1);\n";
  os << "        }\n";
  os << "        tile_regs_release();\n";
  os << "    }\n\n";
  os << "    // Balance the resident constant buffers.\n";
  os << "    cb_pop_front(cb_gamma, kKt);\n";
  os << "    cb_pop_front(cb_scaler, 1);\n";
  os << "}\n";
}

