// The compute.cpp emitter. See include/tensixflow/Codegen/EmitCompute.h for the
// contract. The emitted kernel is derived from the pinned tt-metal v0.82.0-rc2
// programming_examples/matmul/matmul_single_core compute kernel, with the
// circular-buffer indices taken from the plan's allocation.
//
//===----------------------------------------------------------------------===//

#include "tensixflow/Codegen/EmitCompute.h"

#include "tensixflow/Codegen/EmitCommon.h"
#include "tensixflow/TensixflowAttrs.h"
#include "tensixflow/TensixflowSchedule.h"

#include "llvm/Support/raw_ostream.h"

namespace mlir {
namespace tensixflow {

void emitCompute(TensixflowSchedKernelOp kernel,
                 TensixflowScheduleAttr schedule, llvm::raw_ostream &os) {
  (void)kernel;
  llvm::SmallVector<CbSlot> slots = readCbSlots(schedule);
  const int64_t in0Index = slots[0].index;
  const int64_t in1Index = slots[1].index;
  const int64_t outIndex = slots[2].index;

  os << "//===- kernels/compute.cpp - TensixFlow-generated compute kernel ----===//\n";
  os << "//\n";
  os << "// Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "//\n";
  os << "// Role: compute (tile math). Consumes the reader's input tiles, runs the\n";
  os << "// outer product blocked matmul with fp32 destination accumulation, and\n";
  os << "// packs bf16 result tiles into the output circular buffer.\n";
  os << "//\n";
  os << "// Derived from tt-metal v0.82.0-rc2\n";
  os << "// tt_metal/programming_examples/matmul/matmul_single_core/kernels/\n";
  os << "// compute/mm.cpp (Apache-2.0). The circular-buffer indices and the tile\n";
  os << "// counts come from the TensixFlow plan.\n";
  os << "//\n";
  os << "//===----------------------------------------------------------------------===//\n\n";
  os << "#include <cstdint>\n\n";
  os << "#include \"api/compute/compute_kernel_hw_startup.h\"\n";
  os << "#include \"api/compute/matmul.h\"\n";
  os << "#include \"api/compute/tile_move_copy.h\"\n";
  os << "#include \"hostdevcommon/kernel_structs.h\"\n\n";
  os << "using std::uint32_t;\n\n";
  os << "void kernel_main() {\n";
  os << "    // Compile-time args: the (M, K, N) tile decomposition the host sets in\n";
  os << "    // the ComputeConfig. Keeping them as compile-time args lets the JIT\n";
  os << "    // fold the loop bounds.\n";
  os << "    const uint32_t Mt = get_compile_time_arg_val(0);\n";
  os << "    const uint32_t Kt = get_compile_time_arg_val(1);\n";
  os << "    const uint32_t Nt = get_compile_time_arg_val(2);\n\n";
  os << "    // Circular-buffer indices from the plan allocation.\n";
  os << "    constexpr tt::CBIndex cb_in0 = tt::CBIndex::c_" << in0Index << ";\n";
  os << "    constexpr tt::CBIndex cb_in1 = tt::CBIndex::c_" << in1Index << ";\n";
  os << "    constexpr tt::CBIndex cb_out = tt::CBIndex::c_" << outIndex << ";\n\n";
  os << "    // Configure the matrix engine for the input and output circular buffers.\n";
  os << "    compute_kernel_hw_startup<SrcOrder::Reverse>(cb_in0, cb_in1, cb_out);\n";
  os << "    matmul_init(cb_in0, cb_in1);\n\n";
  os << "    // Outer product blocked matmul: one destination tile per iteration,\n";
  os << "    // reducing over the K tiles the reader staged.\n";
  os << "    for (uint32_t mt = 0; mt < Mt; ++mt) {\n";
  os << "        for (uint32_t nt = 0; nt < Nt; ++nt) {\n";
  os << "            // Acquire the destination registers and zero them for this tile.\n";
  os << "            tile_regs_acquire();\n";
  os << "            for (uint32_t kt = 0; kt < Kt; ++kt) {\n";
  os << "                // Wait for the (A, B) input tile pair, accumulate the\n";
  os << "                // product into destination register 0, then release the pair.\n";
  os << "                cb_wait_front(cb_in0, 1);\n";
  os << "                cb_wait_front(cb_in1, 1);\n";
  os << "                matmul_tiles(cb_in0, cb_in1, 0, 0, 0);\n";
  os << "                cb_pop_front(cb_in0, 1);\n";
  os << "                cb_pop_front(cb_in1, 1);\n";
  os << "            }\n\n";
  os << "            // Commit the tile, pack it into the output circular buffer, and\n";
  os << "            // make it visible to the writer.\n";
  os << "            tile_regs_commit();\n";
  os << "            tile_regs_wait();\n";
  os << "            cb_reserve_back(cb_out, 1);\n";
  os << "            pack_tile(0, cb_out);\n";
  os << "            cb_push_back(cb_out, 1);\n";
  os << "            tile_regs_release();\n";
  os << "        }\n";
  os << "    }\n";
  os << "}\n";
}

} // namespace tensixflow
} // namespace mlir
