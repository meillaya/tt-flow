void emitProjectCMakeLists(TensixflowSchedKernelOp kernel,
                           llvm::raw_ostream &os) {
  os << "# Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "#\n";
  os << "# Compile-only structural check for the `" << kernel.getSymName()
     << "` generated kernels.\n";
  // Custom raw-string delimiter `cmake` (terminator `)cmake"`): the content
  // is full of `)"` sequences, which would close a plain R"(...)" early.
  os << R"cmake(#
# There is NO device and NO tt-metal library here: each translation unit is
# checked `-fsyntax-only` against the signature-only stub headers pinned to
# tt-metal @df36cd6. Nothing is linked or run. See README.md.

cmake_minimum_required(VERSION 3.20)
project()cmake"
     << kernel.getSymName()
     << R"cmake(_generated LANGUAGES CXX)
set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

# The signature-only tt-metal stub headers. The default assumes this project
# lives at <tensixflow>/kernels/generated/<name>/; for a project generated
# elsewhere, configure with -DTT_METAL_STUBS_DIR=<path-to-tt_metal_stubs>.
set(TT_METAL_STUBS_DIR "${CMAKE_CURRENT_SOURCE_DIR}/../../handwritten_baselines/tt_metal_stubs"
    CACHE PATH "Path to the signature-only tt-metal stub headers")

if(NOT EXISTS "${TT_METAL_STUBS_DIR}/host_api.hpp")
  message(FATAL_ERROR
    "TT_METAL_STUBS_DIR does not point at the tt-metal stub headers "
    "(host_api.hpp not found under ${TT_METAL_STUBS_DIR}). Configure with "
    "-DTT_METAL_STUBS_DIR=<tensixflow>/kernels/handwritten_baselines/tt_metal_stubs")
endif()

# Syntax-check every kernel against the stubs. `ALL` so a plain build runs it.
add_custom_target(check-compile ALL
  COMMAND ${CMAKE_CXX_COMPILER} -std=c++20 -fsyntax-only -Wall -I "${TT_METAL_STUBS_DIR}" "${CMAKE_CURRENT_SOURCE_DIR}/host.cpp"
  COMMAND ${CMAKE_CXX_COMPILER} -std=c++20 -fsyntax-only -Wall -I "${TT_METAL_STUBS_DIR}" "${CMAKE_CURRENT_SOURCE_DIR}/reader.cpp"
  COMMAND ${CMAKE_CXX_COMPILER} -std=c++20 -fsyntax-only -Wall -I "${TT_METAL_STUBS_DIR}" "${CMAKE_CURRENT_SOURCE_DIR}/compute.cpp"
  COMMAND ${CMAKE_CXX_COMPILER} -std=c++20 -fsyntax-only -Wall -I "${TT_METAL_STUBS_DIR}" "${CMAKE_CURRENT_SOURCE_DIR}/writer.cpp"
  COMMENT "Compile-checking the generated kernels against the signature-only tt-metal stubs, pinned @df36cd6"
  VERBATIM)
)cmake";
}

void emitProjectReadme(TensixflowSchedKernelOp kernel,
                       TensixflowScheduleAttr schedule, llvm::raw_ostream &os) {
  // Plan decisions + tile program, read off the schedule (never hardcoded).
  StringRef fusion = schedule.getFusion().getValue();
  SmallVector<CbSpec> cbs = readCbSpecs(schedule);
  int64_t cbTotal = 0;
  for (const CbSpec &cb : cbs)
    cbTotal += cb.bytes();
  TensixflowSchedReaderOp reader;
  TensixflowSchedComputeOp compute;
  TensixflowSchedWriterOp writer;
  kernel.walk([&](TensixflowSchedReaderOp op) { reader = op; });
  kernel.walk([&](TensixflowSchedComputeOp op) { compute = op; });
  kernel.walk([&](TensixflowSchedWriterOp op) { writer = op; });

  os << "# `" << kernel.getSymName()
     << "` -- TensixFlow-generated TT-Metalium kernel project\n\n";
  os << "Auto-generated by `tensixflow-opt --tensixflow-emit-metalium=output-dir=<dir>`. Do not edit.\n\n";
  os << "## The kernel\n\n";
  os << "| Plan decision | Value |\n|---|---|\n";
  os << "| Kernel | `" << kernel.getSymName() << "` |\n";
  os << "| Fusion | `" << fusion << "` |\n";
  os << "| Core grid | " << schedule.getGridY() << " x " << schedule.getGridX()
     << " |\n";
  os << "| Activation sharding | " << schedule.getActivationSharding().getValue()
     << " |\n";
  os << "| Weight strategy | " << schedule.getWeightStrategy().getValue()
     << " |\n";
  os << "| Intermediate storage | "
     << schedule.getIntermediateStorage().getValue() << " |\n";
  os << "| Modeled DRAM read / write bytes | " << schedule.getDramReadBytes()
     << " / " << schedule.getDramWriteBytes() << " |\n";
  os << "| Modeled NoC multicast bytes | " << schedule.getMulticastBytes()
     << " |\n\n";

  os << "### Circular-buffer allocation (per core)\n\n";
  os << "| CB index | Depth (tiles) | Tile bytes | Bytes |\n|---|---|---|---|\n";
  for (const CbSpec &cb : cbs)
    os << "| c_" << cb.index << " | " << cb.depth << " | " << cb.tileBytes
       << " | " << cb.bytes() << " |\n";
  os << "\nTotal " << cbTotal << " bytes per core, within the "
     << scheduler::kCBShardBudget << "-byte modeled L1 CB budget.\n\n";

  os << "### Tile program\n\n";
  os << "- `reader.cpp` (BRISC data movement): stages activation + weight tiles into the input CBs; tile-loop trip "
     << tripCount(reader) << ".\n";
  os << "- `compute.cpp` (TRISC tile math): the fused tile program for `"
     << fusion << "`; K-streaming tile-loop trip " << tripCount(compute)
     << ".\n";
  os << "- `writer.cpp` (NCRISC data movement): drains result tiles to the destination; tile-loop trip "
     << tripCount(writer) << ".\n\n";

  // Custom delimiter `md` for the same reason as the CMakeLists emitter above.
  os << R"md(## Project layout

- `host.cpp` -- host program: opens the unit mesh device, builds the program
  (kernels + circular buffers + DRAM buffers), sets runtime args, enqueues.
- `reader.cpp` / `compute.cpp` / `writer.cpp` -- the three Tensix `kernel_main`
  roles referenced by the host's `CreateKernel` calls.
- `CMakeLists.txt` -- compile-only check: `cmake -B build && cmake --build build`
  syntax-checks all four kernels against the stub headers (pass
  `-DTT_METAL_STUBS_DIR=<path>` if the project lives outside `kernels/generated/`).

## Current tt-metal API mapping

`host.cpp` (namespace `tt::tt_metal`, current mesh API):
- `distributed::MeshDevice::create_unit_mesh` + `CreateProgram`
- `CreateKernel(program, file, grid, variant<ComputeConfig, DataMovementConfig>)` -- the SINGLE current kernel entry point
- `CreateCircularBuffer` + `CircularBufferConfig` keyed by `tt::CBIndex::c_*`
- `CreateBuffer(InterleavedBufferConfig)` for the DRAM inputs/output
- `SetCommonRuntimeArgs` / `SetRuntimeArgs`
- `distributed::EnqueueWriteMeshBuffer` / `EnqueueMeshWorkload` / `EnqueueReadMeshBuffer`

`reader.cpp` / `writer.cpp` (global dataflow intrinsics):
- `cb_reserve_back` / `cb_push_back` / `cb_wait_front` / `cb_pop_front`
- `get_write_ptr` / `get_read_ptr`
- `get_noc_addr` / `get_noc_multicast_addr`, `noc_async_read` / `noc_async_write` (+ barriers)
- `get_arg_val<T>` / `get_compile_time_arg_val<T>`

`compute.cpp` (global compute intrinsics):
- `matmul_init` / `matmul_tiles`
- `tile_regs_acquire` / `tile_regs_commit` / `tile_regs_wait` / `tile_regs_release`
- `pack_tile`, plus the `cb_*` front/back staging

The legacy program-enqueue API and the per-role `CreateDataMovementKernel` /
`CreateComputeKernel` overloads are intentionally absent.

## Status / honesty (structural validation only)

These kernels are validated **structurally only**: they are compile-checked
(`-fsyntax-only`) against signature-only stub headers pinned to tt-metal
`@df36cd6`. They are NOT executed on hardware and NOT numerically verified.
Numeric correctness is validated at the schedule-IR level: the functional
simulator runs the lowered reader/compute/writer tile program over modeled
circular buffers and is compared against an fp32-exact NumPy golden (PCC).
See the repository README "Status / honesty" and `docs/architecture.md`.
)md";
}

LogicalResult emitProject(TensixflowSchedKernelOp kernel,
                          TensixflowScheduleAttr schedule, StringRef outputDir,
                          std::string &error) {
  // Render ALL six artifacts to memory first: no filesystem touch until every
  // artifact exists, so nothing can leave a half-written tree.
  std::string host, reader, compute, writer, cmake, readme;
  { llvm::raw_string_ostream os(host); emitHost(kernel, schedule, os); }
  { llvm::raw_string_ostream os(reader); emitReader(kernel, schedule, os); }
  { llvm::raw_string_ostream os(compute); emitCompute(kernel, schedule, os); }
  { llvm::raw_string_ostream os(writer); emitWriter(kernel, schedule, os); }
  { llvm::raw_string_ostream os(cmake); emitProjectCMakeLists(kernel, os); }
  { llvm::raw_string_ostream os(readme);
    emitProjectReadme(kernel, schedule, os); }

  // First (and only) filesystem mutation: create the directory tree.
  if (std::error_code ec = llvm::sys::fs::create_directories(outputDir)) {
    error = ("cannot create directory " + Twine(outputDir) + ": " +
             ec.message())
                .str();
    return failure();
  }

  const std::pair<StringRef, StringRef> files[] = {
      {"host.cpp", host},       {"reader.cpp", reader},
      {"compute.cpp", compute}, {"writer.cpp", writer},
      {"CMakeLists.txt", cmake}, {"README.md", readme},
  };
  for (const auto &[name, content] : files)
    if (failed(writeFile(outputDir, name, content, error)))
      return failure();
  return success();
}

