// Write one project file. The generated tree has a subdirectory for the kernel
// sources, so callers create the parent first.
LogicalResult writeFile(llvm::StringRef dir, llvm::StringRef name,
                        llvm::StringRef content, std::string &error) {
  llvm::SmallString<256> path(dir);
  llvm::sys::path::append(path, name);
  std::error_code code;
  llvm::raw_fd_ostream os(path, code, llvm::sys::fs::OF_Text);
  if (code) {
    error = ("cannot open " + path + ": " + code.message()).str();
    return failure();
  }
  os << content;
  os.close();
  if (os.has_error()) {
    error = ("I/O error writing " + path).str();
    return failure();
  }
  return success();
}

// The device the plan was scheduled for, resolved through the generated table.
const device::DeviceSpec *resolveDevice(llvm::StringRef name) {
  const device::DeviceSpec *spec = device::lookup(name);
  if (!spec) {
    spec = device::defaultDevice();
  }
  return spec;
}

