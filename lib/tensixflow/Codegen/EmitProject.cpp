// One circular-buffer slot off the schedule's parallel index/depth/tile-bytes
// arrays. (Deliberate copy of the emitter-local helper -- the todo-34-36
// emitters stay untouched; see the T35/T36 duplication note.)
struct CbSpec {
  int64_t index;
  int64_t depth;
  int64_t tileBytes;
  int64_t bytes() const { return depth * tileBytes; }
};

SmallVector<CbSpec> readCbSpecs(TensixflowScheduleAttr schedule) {
  SmallVector<CbSpec> cbs;
  ArrayAttr indices = schedule.getCbIndices();
  ArrayAttr depths = schedule.getCbDepths();
  ArrayAttr tileBytes = schedule.getCbTileBytes();
  unsigned n = indices.size();
  if (depths.size() < n)
    n = depths.size();
  if (tileBytes.size() < n)
    n = tileBytes.size();
  for (unsigned i = 0; i < n; ++i)
    cbs.push_back({cast<IntegerAttr>(indices[i]).getInt(),
                   cast<IntegerAttr>(depths[i]).getInt(),
                   cast<IntegerAttr>(tileBytes[i]).getInt()});
  if (cbs.size() < 3) {
    cbs.clear();
    cbs.push_back({0, 2, 2048});
    cbs.push_back({1, 2, 2048});
    cbs.push_back({16, 2, 2048});
  }
  return cbs;
}

// The tile-loop trip count driving a reader/compute/writer region; 1 if the
// region is empty/absent.
int64_t tripCount(Operation *op) {
  int64_t trip = 1;
  if (op)
    op->walk([&](TensixflowSchedTileLoopOp loop) {
      trip = loop.getTripCount();
      return WalkResult::interrupt();
    });
  return trip;
}

// Write one project file. On error, set `error` and return failure().
LogicalResult writeFile(StringRef dir, StringRef name, StringRef content,
                        std::string &error) {
  SmallString<256> path(dir);
  llvm::sys::path::append(path, name);
  std::error_code ec;
  llvm::raw_fd_ostream os(path, ec, llvm::sys::fs::OF_Text);
  if (ec) {
    error = ("cannot open " + path + ": " + ec.message()).str();
    return failure();
  }
  os << content;
  os.close();
  if (os.has_error()) {
    error = ("I/O error writing " + path).str();
    return failure();
  }
  return success();
}

