void emitProjectCMakeLists(TensixflowSchedKernelOp kernel,
                           llvm::raw_ostream &os) {
  os << "# Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "#\n";
  os << "# Builds the `" << kernel.getSymName()
     << "` host program against the pinned TT-Metalium release. The three\n";
  os << "# kernel sources in kernels/ are compiled by tt-metal's JIT at run time,\n";
  os << "# not by this build.\n";
  os << "cmake_minimum_required(VERSION 3.22)\n";
  os << "project(tensixflow_generated LANGUAGES CXX)\n";
  os << "set(CMAKE_CXX_STANDARD 20)\n";
  os << "set(CMAKE_CXX_STANDARD_REQUIRED ON)\n";
  os << "\n";
  os << "# The pinned package lives in .deps/tt-metal/<version>/usr of the\n";
  os << "# TensixFlow checkout; scripts/build_generated.sh adds it to\n";
  os << "# CMAKE_PREFIX_PATH. Any other machine can point CMAKE_PREFIX_PATH at a\n";
  os << "# TT-Metalium install instead.\n";
  os << "find_package(TT-Metalium REQUIRED)\n";
  os << "\n";
  os << "add_executable(tensixflow_generated host.cpp)\n";
  os << "target_link_libraries(tensixflow_generated PRIVATE TT::Metalium)\n";
}

void emitProjectReadme(TensixflowSchedKernelOp kernel,
                       TensixflowScheduleAttr schedule, llvm::StringRef deviceName,
                       TensixflowEmissionAttr emission, llvm::raw_ostream &os) {
  std::optional<MatmulShape> shape = readMatmulShape(kernel);
  llvm::SmallVector<CbSlot> slots = readCbSlots(schedule);
  const device::DeviceSpec *spec = resolveDevice(deviceName);
  int64_t cbTotal = 0;
  for (const CbSlot &slot : slots) {
    cbTotal += slot.bytes();
  }

  os << "# `" << kernel.getSymName() << "` TT-Metalium project\n\n";
  os << "Auto-generated by `tensixflow-opt --tensixflow-emit-metalium=output-dir=<dir>`."
     << " Do not edit.\n\n";

  const bool fused = isFusedRmsnormMatmul(schedule);
  os << "## What the program computes\n\n";
  if (fused) {
    os << "Multi-core bf16 fused RMSNorm + MatMul structured like the pinned\n";
    os << "tt-metal v0.82.0-rc2 matmul examples. Each core stages the activation\n";
    os << "rows of its output tiles once in L1, normalizes them there, and runs the\n";
    os << "matmul from the normalized circular buffer, so the normalized\n";
    os << "intermediate never reaches DRAM. The host program fills deterministic\n";
    os << "inputs, splits the output tiles over the plan's core grid with\n";
    os << "`split_work_to_cores`, enqueues the reader, compute, and writer kernels,\n";
    os << "compares the device result against a CPU reference that runs RMSNorm\n";
    os << "then the matmul, and prints the Pearson correlation coefficient (PCC).\n\n";
  } else {
    os << "Multi-core bf16 matrix multiplication structured like the pinned tt-metal\n";
    os << "v0.82.0-rc2 `programming_examples/matmul/matmul_multi_core` example. The\n";
    os << "host program fills deterministic inputs, splits the output tiles over the\n";
    os << "plan's core grid with `split_work_to_cores`, enqueues the reader, compute,\n";
    os << "and writer kernels, compares the device result against a CPU reference\n";
    os << "matmul, and prints the Pearson correlation coefficient (PCC).\n\n";
  }

  os << "## Plan summary\n\n";
  os << "| Item | Value |\n|---|---|\n";
  os << "| Kernel symbol | `@" << kernel.getSymName() << "` |\n";
  os << "| Fusion decision | `" << fusionKind(schedule) << "` |\n";
  os << "| Device | `" << spec->name << "` (" << spec->arch << ") |\n";
  os << "| Realized core grid | " << schedule.getGridY() << " x "
     << schedule.getGridX() << " |\n";
  os << "| Cores used | " << emission.getCoresUsed() << " |\n";
  os << "| Max tiles per core | " << emission.getMaxTilesPerCore() << " |\n";
  os << "| Activation sharding | `" << schedule.getActivationSharding().getValue()
     << "` |\n";
  os << "| Weight strategy | `" << schedule.getWeightStrategy().getValue()
     << "` |\n";
  if (shape) {
    os << "| Matmul shape (elements) | " << shape->m << " x " << shape->n << " x "
       << shape->k << " (M x N x K) |\n";
    os << "| Tiles (M x N x K) | " << shape->mTiles() << " x " << shape->nTiles()
       << " x " << shape->kTiles() << " |\n";
    os << "| Emitted shape (elements) | " << shape->mPadded() << " x "
       << shape->nPadded() << " x " << shape->kPadded()
       << " (rounded up to whole tiles) |\n";
  }
  os << "\n";

  os << "## Emitted path\n\n";
  os << "The host creates the reader, compute, and writer kernels on the plan's\n";
  os << schedule.getGridY() << " x " << schedule.getGridX()
     << " core range and splits the output tiles over it with\n";
  os << "`split_work_to_cores`. Each core owns a contiguous range of linear\n";
  os << "output-tile ids and receives that range as runtime arguments. The\n";
  os << "mapping is `" << emission.getMapping().getValue() << "`.\n\n";
  os << "| Projected emitted-path item | Value |\n|---|---|\n";
  os << "| Cores used | " << emission.getCoresUsed() << " |\n";
  os << "| Max tiles per core | " << emission.getMaxTilesPerCore() << " |\n";
  os << "| DRAM read bytes | " << emission.getDramReadBytes() << " |\n";
  os << "| DRAM write bytes | " << emission.getDramWriteBytes() << " |\n";
  os << "| Fused stage tiles | " << emission.getFusedStageTiles() << " |\n";
  os << "| Fused variant feasible | "
     << (emission.getFusedFeasible() ? "true" : "false") << " |\n\n";
  os << "The input tiles are read unicast, replicated per output tile: each core\n";
  os << "reads the A and B tiles of every output tile it owns, and a tile in K is\n";
  os << "re-read once per output row that needs it. There is no multicast and no\n";
  os << "reuse across output tiles, so the projected DRAM read bytes are an upper\n";
  os << "bound. Every number in this section is projected from static shapes and\n";
  os << "is not a measured count.\n\n";

  os << "## Files\n\n";
  os << "- `host.cpp` builds the program, allocates the DRAM buffers, sets the\n";
  os << "  circular buffers and runtime arguments, enqueues the workload, and runs\n";
  os << "  the self-check.\n";
  if (fused) {
    os << "- `kernels/reader.cpp` stages the core's activation rows, the gamma\n";
    os << "  tiles, and the reduce scaler, then streams the weight tiles into the\n";
    os << "  input circular buffers over the NoC.\n";
    os << "- `kernels/compute.cpp` normalizes each staged row in L1, then runs the\n";
    os << "  tiled matmul from the normalized circular buffer with fp32\n";
    os << "  accumulation and packs bf16 result tiles into the output buffer.\n";
  } else {
    os << "- `kernels/reader.cpp` streams the activation and weight tiles into the\n";
    os << "  input circular buffers over the NoC.\n";
    os << "- `kernels/compute.cpp` runs the tiled matmul with fp32 accumulation and\n";
    os << "  packs bf16 result tiles into the output circular buffer.\n";
  }
  os << "- `kernels/writer.cpp` drains the result tiles to the output DRAM buffer.\n";
  os << "- `CMakeLists.txt` builds the host program with `find_package(TT-Metalium)`\n";
  os << "  and links `TT::Metalium`.\n\n";

  os << "## Circular buffers\n\n";
  os << "| Buffer | tt::CBIndex | Depth (tiles) | Bytes |\n|---|---|---|---|\n";
  if (fused) {
    static constexpr const char *kFusedRoleNames[] = {
        "activation stage", "weight", "gamma",
        "reduce scaler",    "normalized", "output"};
    for (std::size_t i = 0; i < slots.size() && i < kFusedCbSlotCount; ++i) {
      os << "| " << kFusedRoleNames[i] << " | c_" << slots[i].index << " | "
         << slots[i].depth << " | " << slots[i].bytes() << " |\n";
    }
  } else {
    for (const CbSlot &slot : slots) {
      os << "| "
         << (&slot == &slots[0] ? "in0" : (&slot == &slots[1] ? "in1" : "out"))
         << " | c_" << slot.index << " | " << slot.depth << " | " << slot.bytes()
         << " |\n";
    }
  }
  os << "\nTotal " << cbTotal << " bytes per core, against a per-core circular-buffer\n";
  os << "budget of " << spec->cbBudget(device::kDefaultL1ReserveBytes) << " bytes for `"
     << spec->name << "` (" << spec->l1UsableBytes << " usable L1 bytes minus "
     << device::kDefaultL1ReserveBytes << " reserve bytes).\n\n";

  os << "## Build\n\n";
  os << "From the TensixFlow checkout, with the pinned artifacts fetched by\n";
  os << "`scripts/fetch_tt_metal.sh`:\n\n";
  os << "```sh\n";
  os << "devenv shell -- bash scripts/build_generated.sh " << "<project-dir>" << "\n";
  os << "```\n\n";
  os << "The script configures this directory with CMake, builds the host program,\n";
  os << "and links it against the pinned TT-Metalium libraries.\n\n";

  os << "## Run\n\n";
  os << "```sh\n";
  os << "devenv shell -- bash scripts/run_generated.sh " << "<project-dir>" << "\n";
  os << "```\n\n";
  os << "The script runs the program under the official ttsim simulator when the\n";
  os << "simulator library is present in `.deps`, and on a Tenstorrent card when one\n";
  os << "is visible and `--device` is passed. It prints JSON with the run status and\n";
  os << "the PCC the program reported.\n\n";

  os << "## Limits\n\n";
  if (fused) {
    os << "- The fused compute holds one output tile per output column block in\n";
    os << "  the destination registers, so the plan is limited to eight output\n";
    os << "  column tiles. The emitter names the bound in its diagnostic.\n";
    os << "- Each core stages only the activation rows its output tiles need. The\n";
    os << "  weight tiles are still read unicast per output tile, so the naive\n";
    os << "  per-output-tile weight rereads remain; the fusion removes the\n";
    os << "  normalized intermediate's DRAM round trip, not the weight traffic.\n";
  } else {
    os << "- Weight multicast, activation sharding, and the fused paths beyond\n";
    os << "  RMSNorm + MatMul are not emitted.\n";
  }
  os << "- Execution is available through the official simulator with no card\n";
  os << "  present. Hardware execution of this project is untested on this machine.\n";
  os << "- The PCC threshold is a correctness screen, not a performance statement.\n";
}

LogicalResult emitProject(TensixflowSchedKernelOp kernel,
                          TensixflowScheduleAttr schedule,
                          llvm::StringRef deviceName,
                          TensixflowEmissionAttr emission,
                          llvm::StringRef outputDir, std::string &error) {
  // Render every artifact to memory first. The kernel sources land in a
  // kernels/ subdirectory so the host's relative kernel paths are stable.
  std::string host;
  std::string reader;
  std::string compute;
  std::string writer;
  std::string cmakeLists;
  std::string readme;
  {
    llvm::raw_string_ostream os(host);
    emitHost(kernel, schedule, os);
  }
  {
    llvm::raw_string_ostream os(reader);
    emitReader(kernel, schedule, os);
  }
  {
    llvm::raw_string_ostream os(compute);
    emitCompute(kernel, schedule, os);
  }
  {
    llvm::raw_string_ostream os(writer);
    emitWriter(kernel, schedule, os);
  }
  {
    llvm::raw_string_ostream os(cmakeLists);
    emitProjectCMakeLists(kernel, os);
  }
  {
    llvm::raw_string_ostream os(readme);
    emitProjectReadme(kernel, schedule, deviceName, emission, os);
  }

  // First filesystem mutation: create the directory tree.
  if (std::error_code code = llvm::sys::fs::create_directories(outputDir)) {
    error = ("cannot create directory " + llvm::Twine(outputDir) + ": " +
             code.message())
                .str();
    return failure();
  }
  llvm::SmallString<256> kernelsDir(outputDir);
  llvm::sys::path::append(kernelsDir, "kernels");
  if (std::error_code code = llvm::sys::fs::create_directories(kernelsDir)) {
    error = ("cannot create directory " + llvm::Twine(kernelsDir) + ": " +
             code.message())
                .str();
    return failure();
  }

  if (failed(writeFile(outputDir, "host.cpp", host, error))) {
    return failure();
  }
  if (failed(writeFile(outputDir, "CMakeLists.txt", cmakeLists, error))) {
    return failure();
  }
  if (failed(writeFile(outputDir, "README.md", readme, error))) {
    return failure();
  }
  if (failed(writeFile(kernelsDir, "reader.cpp", reader, error))) {
    return failure();
  }
  if (failed(writeFile(kernelsDir, "compute.cpp", compute, error))) {
    return failure();
  }
  if (failed(writeFile(kernelsDir, "writer.cpp", writer, error))) {
    return failure();
  }
  return success();
}

