void emitFusedReader(TensixflowScheduleAttr schedule,
                     const MatmulShape &shape, llvm::raw_ostream &os) {
  llvm::SmallVector<CbSlot> slots = readCbSlots(schedule);
  const CbSlot &act = slots[kFusedActivationSlot];
  const CbSlot &weight = slots[kFusedWeightSlot];
  const CbSlot &gamma = slots[kFusedGammaSlot];
  const CbSlot &scaler = slots[kFusedScalerSlot];

  os << "//===- kernels/reader.cpp - TensixFlow-generated fused RMSNorm + ";
  os << "MatMul reader ------===//\n";
  os << "//\n";
  os << "// Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "//\n";
  os << "// Role: fused reader (data movement). Phase 1 stages the core's\n";
  os << "// distinct activation rows, the gamma tiles, and the unit reduce\n";
  os << "// scaler. Phase 2 streams the weight tiles in the order the fused\n";
  os << "// compute kernel consumes them: per output row, per K block, per\n";
  os << "// output column tile.\n";
  os << "//\n";
  os << "//===----------------------------------------------------------------------===//\n\n";
  os << "#include <stdint.h>\n\n";
  os << "#include \"api/dataflow/dataflow_api.h\"\n";
  os << "#include \"hostdevcommon/kernel_structs.h\"\n\n";
  os << "void kernel_main() {\n";
  os << "    // Runtime args: the DRAM buffer addresses, the (M, K, N) tile\n";
  os << "    // decomposition, and the output-tile range this core owns.\n";
  os << "    const uint32_t act_addr = get_arg_val<uint32_t>(0);\n";
  os << "    const uint32_t weight_addr = get_arg_val<uint32_t>(1);\n";
  os << "    const uint32_t gamma_addr = get_arg_val<uint32_t>(2);\n";
  os << "    const uint32_t scaler_addr = get_arg_val<uint32_t>(3);\n";
  os << "    const uint32_t Mt = get_arg_val<uint32_t>(4);\n";
  os << "    const uint32_t Kt = get_arg_val<uint32_t>(5);\n";
  os << "    const uint32_t Nt = get_arg_val<uint32_t>(6);\n";
  os << "    const uint32_t startTile = get_arg_val<uint32_t>(7);\n";
  os << "    const uint32_t tileCount = get_arg_val<uint32_t>(8);\n";
  os << "    if (tileCount == 0) {\n";
  os << "        return;\n";
  os << "    }\n\n";
  os << "    // Circular-buffer indices from the plan's fused allocation.\n";
  os << "    constexpr uint32_t cb_act = static_cast<uint32_t>(tt::CBIndex::c_"
     << act.index << ");\n";
  os << "    constexpr uint32_t cb_weight = static_cast<uint32_t>(tt::CBIndex::c_"
     << weight.index << ");\n";
  os << "    constexpr uint32_t cb_gamma = static_cast<uint32_t>(tt::CBIndex::c_"
     << gamma.index << ");\n";
  os << "    constexpr uint32_t cb_scaler = static_cast<uint32_t>(tt::CBIndex::c_"
     << scaler.index << ");\n\n";
  os << "    // One TensorAccessor per DRAM buffer, in the order the host\n";
  os << "    // appended the compile-time args.\n";
  os << "    constexpr auto act_args = TensorAccessorArgs<0>();\n";
  os << "    const auto act = TensorAccessor(act_args, act_addr);\n";
  os << "    constexpr auto weight_args =\n";
  os << "        TensorAccessorArgs<act_args.next_compile_time_args_offset()>();\n";
  os << "    const auto weight = TensorAccessor(weight_args, weight_addr);\n";
  os << "    constexpr auto gamma_args =\n";
  os << "        TensorAccessorArgs<weight_args.next_compile_time_args_offset()>();\n";
  os << "    const auto gamma = TensorAccessor(gamma_args, gamma_addr);\n";
  os << "    constexpr auto scaler_args =\n";
  os << "        TensorAccessorArgs<gamma_args.next_compile_time_args_offset()>();\n";
  os << "    const auto scaler = TensorAccessor(scaler_args, scaler_addr);\n\n";
  os << "    // The core owns a contiguous linear output-tile range, so its\n";
  os << "    // activation rows are consecutive. Phase 1 stages each distinct row\n";
  os << "    // once, then the gamma tiles and the unit reduce scaler.\n";
  os << "    const uint32_t firstRow = startTile / Nt;\n";
  os << "    const uint32_t lastRow = (startTile + tileCount - 1) / Nt;\n";
  os << "    (void)Mt;\n";
  os << "    for (uint32_t row = firstRow; row <= lastRow; ++row) {\n";
  os << "        for (uint32_t kt = 0; kt < Kt; ++kt) {\n";
  os << "            cb_reserve_back(cb_act, 1);\n";
  os << "            noc_async_read_page(row * Kt + kt, act, get_write_ptr(cb_act));\n";
  os << "            noc_async_read_barrier();\n";
  os << "            cb_push_back(cb_act, 1);\n";
  os << "        }\n";
  os << "    }\n";
  os << "    for (uint32_t kt = 0; kt < Kt; ++kt) {\n";
  os << "        cb_reserve_back(cb_gamma, 1);\n";
  os << "        noc_async_read_page(kt, gamma, get_write_ptr(cb_gamma));\n";
  os << "        noc_async_read_barrier();\n";
  os << "        cb_push_back(cb_gamma, 1);\n";
  os << "    }\n";
  os << "    cb_reserve_back(cb_scaler, 1);\n";
  os << "    noc_async_read_page(0, scaler, get_write_ptr(cb_scaler));\n";
  os << "    noc_async_read_barrier();\n";
  os << "    cb_push_back(cb_scaler, 1);\n\n";
  os << "    // Phase 2: stream the weight tiles in compute order. B is KxN, so\n";
  os << "    // tile (kt, col) is at linear index kt * Nt + col.\n";
  os << "    for (uint32_t row = firstRow; row <= lastRow; ++row) {\n";
  os << "        const uint32_t firstCol = (row == firstRow) ? startTile % Nt : 0;\n";
  os << "        const uint32_t lastCol =\n";
  os << "            (row == lastRow) ? (startTile + tileCount - 1) % Nt : Nt - 1;\n";
  os << "        for (uint32_t kt = 0; kt < Kt; ++kt) {\n";
  os << "            for (uint32_t col = firstCol; col <= lastCol; ++col) {\n";
  os << "                cb_reserve_back(cb_weight, 1);\n";
  os << "                noc_async_read_page(kt * Nt + col, weight, get_write_ptr(cb_weight));\n";
  os << "                noc_async_read_barrier();\n";
  os << "                cb_push_back(cb_weight, 1);\n";
  os << "            }\n";
  os << "        }\n";
  os << "    }\n";
  os << "}\n";
}

// Emit the shared activation-staging loop of the blocked-reuse readers: read
// the core's full activation row block into in0. The row block is unicast in
// every variant; only the weight column block changes with multicast.
void emitActivationStageBlock(llvm::raw_ostream &os) {
  os << "    // Stage the activation row block into in0. A is MxK, so output row\n";
  os << "    // (rowStart + mt) starts at linear tile (rowStart + mt) * Kt.\n";
  os << "    for (uint32_t mt = 0; mt < rowCount; ++mt) {\n";
  os << "        for (uint32_t kt = 0; kt < Kt; ++kt) {\n";
  os << "            cb_reserve_back(cb_id_in0, 1);\n";
  os << "            noc_async_read_page((rowStart + mt) * Kt + kt, a,\n";
  os << "                                get_write_ptr(cb_id_in0));\n";
  os << "            noc_async_read_barrier();\n";
  os << "            cb_push_back(cb_id_in0, 1);\n";
  os << "        }\n";
  os << "    }\n";
}

