  os << "// its full activation row block into in0 and its full weight column\n";
  os << "// block into in1, then exits; the compute kernel accumulates every\n";
  os << "// output tile of the 2D block from those resident buffers.\n";
  os << "//\n";
  os << "// Derived from tt-metal v0.82.0-rc2\n";
  os << "// tt_metal/programming_examples/matmul/matmul_multicore_reuse and\n";
