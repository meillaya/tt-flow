  os << "    // output-tile coordinates, and the reduction tile count.\n";
  os << "    const uint32_t src0_addr = get_arg_val<uint32_t>(0);\n";
  os << "    const uint32_t src1_addr = get_arg_val<uint32_t>(1);\n";
  os << "    const uint32_t Nt = get_arg_val<uint32_t>(2);\n";
  os << "    const uint32_t rowStart = get_arg_val<uint32_t>(3);\n";
  os << "    const uint32_t rowCount = get_arg_val<uint32_t>(4);\n";
