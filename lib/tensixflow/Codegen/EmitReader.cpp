void emitReader(TensixflowSchedKernelOp kernel, TensixflowScheduleAttr schedule,
                const MatmulEmission &mapping, llvm::raw_ostream &os) {
  // The fused MLP reader stages its own blocks; the matmul readers below cover
  // the pure matmul and fused RMSNorm paths.
  if (isFusedMlp(schedule)) {
    std::optional<MlpShape> shape = readMlpShape(kernel);
    if (shape) {
      emitMlpReader(schedule, *shape, mapping, os);
      return;
    }
  }
  if (isFusedRmsnormMatmul(schedule)) {
    std::optional<MatmulShape> shape = readMatmulShape(kernel);
    if (shape) {
      emitFusedReader(schedule, *shape, os);
      return;
    }
  }
  (void)kernel;
  if (mapping.blockedReuse()) {
    emitBlockedReuseReader(schedule, os);
    return;
  }
  llvm::SmallVector<CbSlot> slots = readCbSlots(schedule);
  const int64_t in0Index = slots[0].index;
  const int64_t in1Index = slots[1].index;

  os << "//===- kernels/reader.cpp - TensixFlow-generated reader kernel ------===//\n";
  os << "//\n";
  os << "// Auto-generated by tensixflow-opt --tensixflow-emit-metalium. Do not edit.\n";
  os << "//\n";
  os << "// Role: reader (data movement). Each core streams the activation and\n";
  os << "// weight tiles of the output tiles it owns into the input circular\n";
  os << "// buffers.\n";
  os << "//\n";
  os << "// Derived from tt-metal v0.82.0-rc2\n";
  os << "// tt_metal/programming_examples/matmul/matmul_multi_core/kernels/\n";
  os << "// dataflow/reader_mm_output_tiles_partitioned.cpp (Apache-2.0). The\n";
  os << "// circular-buffer indices and the per-core output-tile range come from\n";
  os << "// the TensixFlow plan.\n";
  os << "//\n";
  os << "//===----------------------------------------------------------------------===//\n\n";
  os << "#include <stdint.h>\n\n";
  os << "#include \"api/dataflow/dataflow_api.h\"\n";
  os << "#include \"hostdevcommon/kernel_structs.h\"\n\n";
  os << "void kernel_main() {\n";
  os << "    // Runtime args: the two DRAM buffer addresses, the (M, K, N) tile\n";
  os << "    // decomposition, and the output-tile range this core owns, in the\n";
  os << "    // order the host sets them.\n";
  os << "    uint32_t src0_addr = get_arg_val<uint32_t>(0);\n";
  os << "    uint32_t src1_addr = get_arg_val<uint32_t>(1);\n";
  os << "    uint32_t Mt = get_arg_val<uint32_t>(2);\n";
  os << "    uint32_t Kt = get_arg_val<uint32_t>(3);\n";
  os << "    uint32_t Nt = get_arg_val<uint32_t>(4);\n";
  os << "    uint32_t output_tile_start_id = get_arg_val<uint32_t>(5);\n";
  os << "    uint32_t num_output_tiles = get_arg_val<uint32_t>(6);\n\n";
  os << "    // Circular-buffer indices from the plan allocation.\n";
  os << "    constexpr uint32_t cb_id_in0 = static_cast<uint32_t>(tt::CBIndex::c_"
     << in0Index << ");\n";
  os << "    constexpr uint32_t cb_id_in1 = static_cast<uint32_t>(tt::CBIndex::c_"
     << in1Index << ");\n\n";
  os << "    // One TensorAccessor per DRAM input buffer. The host appended the\n";
  os << "    // matching compile-time args in this order.\n";
  os << "    constexpr auto a_args = TensorAccessorArgs<0>();\n";
  os << "    const auto a = TensorAccessor(a_args, src0_addr);\n";
  os << "    constexpr auto b_args =\n";
  os << "        TensorAccessorArgs<a_args.next_compile_time_args_offset()>();\n";
  os << "    const auto b = TensorAccessor(b_args, src1_addr);\n\n";
  os << "    // Walk this core's contiguous output-tile range. A linear output tile\n";
  os << "    // id maps to (out_row, out_col) in row-major order, so the kernel reads\n";
  os << "    // A[out_row][k] and B[k][out_col] for every reduction tile k.\n";
  os << "    for (uint32_t output_tile = 0; output_tile < num_output_tiles;\n";
  os << "         output_tile++) {\n";
  os << "        uint32_t current_tile_id = output_tile_start_id + output_tile;\n";
  os << "        uint32_t out_row = current_tile_id / Nt;\n";
  os << "        uint32_t out_col = current_tile_id % Nt;\n";
  os << "        (void)Mt;\n\n";
  os << "        for (uint32_t k = 0; k < Kt; k++) {\n";
  os << "            {\n";
  os << "                // A tile at (out_row, k). A is MxK, so the index strides by Kt.\n";
  os << "                uint32_t tile_a = out_row * Kt + k;\n";
  os << "                cb_reserve_back(cb_id_in0, 1);\n";
  os << "                uint32_t l1_write_addr_in0 = get_write_ptr(cb_id_in0);\n";
  os << "                noc_async_read_page(tile_a, a, l1_write_addr_in0);\n";
  os << "                noc_async_read_barrier();\n";
  os << "                cb_push_back(cb_id_in0, 1);\n";
  os << "            }\n";
  os << "            {\n";
  os << "                // B tile at (k, out_col). B is KxN, so the index strides by Nt.\n";
  os << "                uint32_t tile_b = k * Nt + out_col;\n";
  os << "                cb_reserve_back(cb_id_in1, 1);\n";
  os << "                uint32_t l1_write_addr_in1 = get_write_ptr(cb_id_in1);\n";
  os << "                noc_async_read_page(tile_b, b, l1_write_addr_in1);\n";
  os << "                noc_async_read_barrier();\n";
  os << "                cb_push_back(cb_id_in1, 1);\n";
  os << "            }\n";
  os << "        }\n";
  os << "    }\n";
  os << "}\n";
}

